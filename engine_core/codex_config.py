"""Codex CLI configuration — OpenRouter providers generated from engine profiles.

Writes a marked block into ~/.codex/config.toml (one `[model_providers.engine_<p>]`
per configured profile + a `[profiles.engine_<p>]` selector), and an env-var file
`~/.codex/engine-ai-env.sh` (0600) the user can source. Codex reads custom-provider
keys from env vars (`env_key`), so each profile's key has a stable var name.

NEVER touches ~/.codex/auth.json — that holds the user's OpenAI login. Existing
config.toml content outside our markers is preserved byte-for-byte; re-running
replaces only our block (idempotent), with a backup kept on first write.
"""

from __future__ import annotations

import os
import shutil
import time

from engine_core.profiles import vault_name

OPENROUTER_BASE = "https://openrouter.ai/api/v1"
BEGIN = "# >>> engine-ai (openrouter providers) >>>"
END = "# <<< engine-ai (openrouter providers) <<<"


def _slug(profile: str) -> str:
    return profile.replace("-", "_").replace(".", "_")


def render_block(configured: list[dict], active: str | None,
                 include_top: bool = True) -> str:
    """TOML block for every configured profile. `configured` rows come from
    Assignments.status() and must already have key != MISSING and a model id.

    `include_top=False` omits the top-level `model`/`model_provider` keys (used when
    the user's existing config already sets them — duplicate top-level keys are a
    TOML error, and silently overriding their default model would be worse)."""
    if not configured:
        raise ValueError("no configured profiles (import keys first)")
    active = active or configured[0]["profile"]
    names = {c["profile"] for c in configured}
    if active not in names:
        raise ValueError(f"active profile {active!r} is not configured ({sorted(names)})")
    lines = [BEGIN, f"# generated by engine-ai at {time.strftime('%Y-%m-%d %H:%M:%S')}",
             "# keys: source ~/.codex/engine-ai-env.sh (or export the env_key vars)", ""]
    by_profile = {c["profile"]: c for c in configured}
    if include_top:
        act = by_profile[active]
        lines += [f'model = "{act["model"]}"',
                  f'model_provider = "engine_{_slug(active)}"', ""]
    for name in sorted(names):
        c = by_profile[name]
        lines += [f"[model_providers.engine_{_slug(name)}]",
                  f'name = "OpenRouter · {name} (engine-ai)"',
                  f'base_url = "{OPENROUTER_BASE}"',
                  f'env_key = "{vault_name(name)}"',
                  'wire_api = "chat"', "",
                  f"[profiles.engine_{_slug(name)}]",
                  f'model = "{c["model"]}"',
                  f'model_provider = "engine_{_slug(name)}"', ""]
    lines += [END, ""]
    return "\n".join(lines)


def _merge(existing: str, block: str) -> str:
    """Place our marked block FIRST (top-level keys must precede any table) or
    replace the previous marked block in place; keep user content untouched."""
    if BEGIN in existing and END in existing:
        pre = existing.split(BEGIN)[0]
        post = existing.split(END, 1)[1].lstrip("\n")
        return pre + block + ("\n" + post if post.strip() else "")
    if existing.strip():
        return block + "\n" + existing.rstrip("\n") + "\n"
    return block


def write_config(codex_dir: str, configured: list[dict], active: str | None = None) -> dict:
    """Write the config.toml block + env file. Preserves user config; backs up once."""
    os.makedirs(codex_dir, exist_ok=True)
    cfg_path = os.path.join(codex_dir, "config.toml")

    existing = ""
    if os.path.exists(cfg_path):
        with open(cfg_path, encoding="utf-8") as f:
            existing = f.read()
        backup = cfg_path + ".engine-ai.bak"
        if not os.path.exists(backup):  # first write keeps the pristine original
            shutil.copy2(cfg_path, backup)

    # never emit duplicate top-level keys: if the user's config already selects a
    # model, keep theirs and provide our profiles as selectors only
    include_top = True
    if existing.strip():
        try:
            import tomllib
            include_top = "model" not in tomllib.loads(existing)
        except Exception:  # noqa: BLE001 - unparseable user config: don't add top keys
            include_top = False
    block = render_block(configured, active, include_top=include_top)

    merged = _merge(existing, block)
    tmp = cfg_path + ".engine-ai.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(merged)
    os.replace(tmp, cfg_path)

    out = {"ok": True, "config": cfg_path, "merged": BEGIN in existing,
           "providers": sorted(f"engine_{_slug(c['profile'])}" for c in configured),
           "active": active or configured[0]["profile"]}
    if existing.strip():
        out["backup"] = os.path.join(codex_dir, "config.toml.engine-ai.bak")
    if not include_top:
        out["note"] = ("kept the existing top-level model/model_provider (your config "
                       "already sets one) — switch with: codex --profile engine_<name>")
    return out


def write_env_file(codex_dir: str, keys: dict[str, str]) -> dict:
    """Write ~/.codex/engine-ai-env.sh with one export per profile key (0600).

    `keys` maps profile name → the actual API key; this is the only plaintext
    copy, chmod 600, and the user can delete it after adding the exports to
    their shell profile.
    """
    os.makedirs(codex_dir, exist_ok=True)
    path = os.path.join(codex_dir, "engine-ai-env.sh")
    lines = ["# engine-ai: OpenRouter keys for Codex CLI (delete after sourcing into",
          "# your shell profile, or keep — this file is chmod 600)"]
    for profile, key in sorted(keys.items()):
        lines.append(f'export {vault_name(profile)}="{key}"')
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, path)
    return {"ok": True, "env_file": path, "vars": [vault_name(p) for p in sorted(keys)]}
